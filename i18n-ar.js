  function money(t) {
    var fmt = function (v) { return (Math.round(v * 100) / 100).toString(); };
    return t
      .replace(/AED\s?(\d+)k\s?[-–]\s?(\d+)k/g, '$1–$2 ألف درهم')
      .replace(/AED\s?([\d,]+)\s?[-–]\s?([\d,]+)(?![\d,]*[kKM])/g, '$1–$2 درهم')
      .replace(/([−-]?)AED\s?([\d,]+(?:\.\d+)?)\s?([kKM])?(\+)?(\/mo)?/g, function (m, sign, num, suf, plus, mo) {
        var v = parseFloat(num.replace(/,/g, '')), out;
        if (suf === 'M' || (suf && v >= 1000)) out = fmt(suf === 'M' ? v : v / 1000) + ' مليون درهم';
        else if (suf) out = fmt(v) + ' ألف درهم';
        else out = num + ' درهم';
        return (plus ? 'أكثر من ' : '') + sign + out + (mo ? ' شهريًا' : '');
      })
      .replace(/\(AED\)/g, '(درهم)').replace(/\bAED\b/g, 'درهم');
  }
